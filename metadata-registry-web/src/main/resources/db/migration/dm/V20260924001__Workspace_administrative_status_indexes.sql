DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='MDR' AND INDEX_NAME='IDX_REGISTRATION_STATE_ADMINISTRATIVE_STATUS';
  IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX MDR.IDX_REGISTRATION_STATE_ADMINISTRATIVE_STATUS ON MDR.REGISTRATION_STATE (ADMINISTRATIVE_STATUS)'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

