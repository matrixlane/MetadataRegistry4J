-- 达梦：逐语句独立 PL/SQL 块守卫，幂等；DDL 走动态 SQL。待达梦实例实测（KNOWN_FAILURES 同款遗留）。
-- 先动态删除引用这三表的全部外键（Hibernate ddl-auto 生成的 FK 命名不可预测）。
DECLARE
  CURSOR c_fk IS
    SELECT acc.owner, acc.table_name, acc.constraint_name
    FROM all_constraints acc
    WHERE acc.constraint_type = 'R'
      AND acc.r_owner = 'MDR'
      AND acc.r_constraint_name IN (
        SELECT ac.constraint_name FROM all_constraints ac
        WHERE ac.constraint_type IN ('P','U')
          AND ac.owner = 'MDR'
          AND ac.table_name IN ('ITEM_MAPPING','ITEM_MAPPING_SUBJECT','ITEM_MAPPING_OBJECT'));
BEGIN
  FOR r IN c_fk LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.owner || '.' || r.table_name ||
                      ' DROP CONSTRAINT ' || r.constraint_name;
  END LOOP;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='MDR' AND TABLE_NAME='ITEM_MAPPING_SUBJECT';
  IF n = 1 THEN EXECUTE IMMEDIATE 'DROP TABLE MDR.ITEM_MAPPING_SUBJECT'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
