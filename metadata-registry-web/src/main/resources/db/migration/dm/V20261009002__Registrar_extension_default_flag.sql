-- 默认注册人员标志卫星表（personal-no-login-registrar-default，详见 sqlite 同名脚本头注释）：
-- 建 EXT.REGISTRAR（1:1 按 id）+ 存量三级回填，每账号至多一默认。待达梦实例实测（项目惯例）。
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'REGISTRAR';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.REGISTRAR (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        IS_DEFAULT BIT DEFAULT 0 NOT NULL)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ① 原 ACTIVE_REGISTRAR_ID（列于 V20261009003 才删除，此处仍在）
DECLARE
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'ACCOUNT' AND COLUMN_NAME = 'ACTIVE_REGISTRAR_ID';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO EXT.REGISTRAR (ID, IS_DEFAULT)
      SELECT a.ACTIVE_REGISTRAR_ID, 1
        FROM EXT.ACCOUNT a
       WHERE a.ACTIVE_REGISTRAR_ID IS NOT NULL
         AND EXISTS (SELECT 1 FROM EXT.CONTACT_ACCOUNT_BINDING b
                      WHERE b.CONTACT_ID = a.ACTIVE_REGISTRAR_ID
                        AND b.ACCOUNT_ID = a.ID)
         AND NOT EXISTS (SELECT 1 FROM EXT.REGISTRAR r WHERE r.ID = a.ACTIVE_REGISTRAR_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ② 原默认绑定对应的 Registrar（该账号未被 ① 覆盖者；同账号多默认存量只取 CONTACT_ID 最小者）
DECLARE
  src NUMBER; col NUMBER;
BEGIN
  SELECT COUNT(*) INTO src FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='CONTACT_ACCOUNT_BINDING';
  SELECT COUNT(*) INTO col FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'ACCOUNT' AND COLUMN_NAME = 'ACTIVE_REGISTRAR_ID';
  IF src = 1 AND col = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO EXT.REGISTRAR (ID, IS_DEFAULT)
      SELECT pick.CONTACT_ID, 1
        FROM (
              SELECT b.ACCOUNT_ID, MIN(b.CONTACT_ID) AS CONTACT_ID
                FROM EXT.CONTACT_ACCOUNT_BINDING b
               WHERE b.IS_DEFAULT = 1
                 AND EXISTS (SELECT 1 FROM MDR.REGISTRAR reg WHERE reg.ID = b.CONTACT_ID)
                 AND NOT EXISTS (SELECT 1 FROM EXT.ACCOUNT a
                                  WHERE a.ID = b.ACCOUNT_ID
                                    AND a.ACTIVE_REGISTRAR_ID = b.CONTACT_ID)
                 AND NOT EXISTS (SELECT 1 FROM EXT.CONTACT_ACCOUNT_BINDING b3
                                  JOIN EXT.REGISTRAR r3 ON r3.ID = b3.CONTACT_ID AND r3.IS_DEFAULT = 1
                                 WHERE b3.ACCOUNT_ID = b.ACCOUNT_ID)
               GROUP BY b.ACCOUNT_ID
             ) pick
       WHERE NOT EXISTS (SELECT 1 FROM EXT.REGISTRAR r WHERE r.ID = pick.CONTACT_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ③ 账号首个 Registrar（该账号尚无任一默认时；CONTACT_ID 最小者）
DECLARE
  src NUMBER; col NUMBER;
BEGIN
  SELECT COUNT(*) INTO src FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='CONTACT_ACCOUNT_BINDING';
  SELECT COUNT(*) INTO col FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'ACCOUNT' AND COLUMN_NAME = 'ACTIVE_REGISTRAR_ID';
  IF src = 1 AND col = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO EXT.REGISTRAR (ID, IS_DEFAULT)
      SELECT first_reg.CONTACT_ID, 1
        FROM (
              SELECT b.ACCOUNT_ID, MIN(b.CONTACT_ID) AS CONTACT_ID
                FROM EXT.CONTACT_ACCOUNT_BINDING b
               WHERE EXISTS (SELECT 1 FROM MDR.REGISTRAR reg WHERE reg.ID = b.CONTACT_ID)
               GROUP BY b.ACCOUNT_ID
             ) first_reg
       WHERE NOT EXISTS (SELECT 1 FROM EXT.CONTACT_ACCOUNT_BINDING b2
                          JOIN EXT.REGISTRAR r2 ON r2.ID = b2.CONTACT_ID AND r2.IS_DEFAULT = 1
                         WHERE b2.ACCOUNT_ID = first_reg.ACCOUNT_ID)
         AND NOT EXISTS (SELECT 1 FROM EXT.REGISTRAR r WHERE r.ID = first_reg.CONTACT_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
