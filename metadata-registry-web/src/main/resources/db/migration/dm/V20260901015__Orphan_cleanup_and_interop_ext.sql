-- 二、interop 两表迁入 EXT(CTAS + 约束重建 + DROP;EXT 模式须已预建)
DECLARE
  src NUMBER; dst NUMBER;
BEGIN
  SELECT COUNT(*) INTO src FROM ALL_TABLES WHERE OWNER='MDR' AND TABLE_NAME='INTEROP_DATA_SET';
  SELECT COUNT(*) INTO dst FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='INTEROP_DATA_SET';
  IF src = 1 AND dst = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.INTEROP_DATA_SET AS SELECT * FROM MDR.INTEROP_DATA_SET';
    EXECUTE IMMEDIATE 'ALTER TABLE EXT.INTEROP_DATA_SET ADD PRIMARY KEY (ID)';
    EXECUTE IMMEDIATE 'DROP TABLE MDR.INTEROP_DATA_SET';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

