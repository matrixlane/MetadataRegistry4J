    EXECUTE IMMEDIATE 'ALTER TABLE EXT.INTEROP_DATA_ELEMENT ADD CONSTRAINT UK_INTEROP_DE_DATASET_IDENTIFIER UNIQUE (DATA_SET_ID, DE_IDENTIFIER)';
    EXECUTE IMMEDIATE 'ALTER TABLE EXT.INTEROP_DATA_ELEMENT ADD CONSTRAINT FK_IDE_DATA_SET FOREIGN KEY (DATA_SET_ID) REFERENCES EXT.INTEROP_DATA_SET (ID)';
    EXECUTE IMMEDIATE 'DROP TABLE MDR.INTEROP_DATA_ELEMENT';
  END IF;
