-- 0. 目标 id 收集表（含防御过滤；重跑先清残留）
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'TMP_SYS_DEFAULT_NS';
  IF tbl_exists = 1 THEN
    EXECUTE IMMEDIATE 'DROP TABLE MDR.TMP_SYS_DEFAULT_NS';
  END IF;
  EXECUTE IMMEDIATE 'CREATE TABLE MDR.TMP_SYS_DEFAULT_NS AS
    SELECT ns.ID FROM MDR.NAMESPACE ns
    WHERE ns.SCHEME_REFERENCE = ''urn:metadata-registry:system-default''
      AND NOT EXISTS (SELECT 1 FROM MDR.SCOPED_IDENTIFIER si WHERE si.NAMESPACE_ID = ns.ID)';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

