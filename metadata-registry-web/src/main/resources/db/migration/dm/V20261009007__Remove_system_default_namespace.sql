-- ============================================================================
-- 历史系统组织（固定 UUID …0001，CHAR(36)）：仅当无任何引用
-- （namespace.naming_authority_id、contact.organization_id）时清理（design D5）。
-- 有引用的存量行保留，但不再享受代码侧特殊保护（OrganizationService 过滤与
-- 删除保护已随本 change 移除）。
-- ============================================================================
DECLARE
  org_count NUMBER;
  ns_ref NUMBER;
  ct_ref NUMBER;
BEGIN
  SELECT COUNT(*) INTO org_count FROM MDR.ORGANIZATION
    WHERE ID = '00000000-0000-0000-0000-000000000001';
  SELECT COUNT(*) INTO ns_ref FROM MDR.NAMESPACE
    WHERE NAMING_AUTHORITY_ID = '00000000-0000-0000-0000-000000000001';
  SELECT COUNT(*) INTO ct_ref FROM MDR.CONTACT
    WHERE ORGANIZATION_ID = '00000000-0000-0000-0000-000000000001';
  IF org_count = 1 AND ns_ref = 0 AND ct_ref = 0 THEN
    EXECUTE IMMEDIATE 'DELETE FROM MDR.ORGANIZATION_NAME
      WHERE ORGANIZATION_ID = ''00000000-0000-0000-0000-000000000001''';
    EXECUTE IMMEDIATE 'DELETE FROM MDR.ORGANIZATION_EMAIL
      WHERE ORGANIZATION_ID = ''00000000-0000-0000-0000-000000000001''';
    EXECUTE IMMEDIATE 'DELETE FROM MDR.ORGANIZATION_PHONE
      WHERE ORGANIZATION_ID = ''00000000-0000-0000-0000-000000000001''';
    EXECUTE IMMEDIATE 'DELETE FROM MDR.ORGANIZATION
      WHERE ID = ''00000000-0000-0000-0000-000000000001''';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
