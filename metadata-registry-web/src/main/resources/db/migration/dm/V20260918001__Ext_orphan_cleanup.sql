-- ext schema 孤儿表物理清理(V20260901015 漏网):ITEM_CLASSIFICATION、SEQUENCE_REGISTRY。
-- 两表均无 JPA 实体与代码引用,为历史改名/功能下线残留;存在于部分存量库。
-- 逐表独立 PL/SQL 块守卫,幂等;异常吞掉跳过。
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='ITEM_CLASSIFICATION';
  IF n = 1 THEN EXECUTE IMMEDIATE 'DROP TABLE EXT."ITEM_CLASSIFICATION"'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
