-- 2.4 Scoped_Identifier 扩展属性剥为卫星实体(ISO/IEC 11179 标准实体只留标准属性)
DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'SCOPED_IDENTIFIER_LIFECYCLE';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MDR.SCOPED_IDENTIFIER_LIFECYCLE (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        SCOPED_IDENTIFIER_ID CHAR(36) NOT NULL,
        IDENTIFIER_CREATION_MODE VARCHAR(16),
        VERSION_CREATION_MODE VARCHAR(16),
        VERSION_STATUS VARCHAR(16),
        CREATED_AT TIMESTAMP,
        PUBLISHED_AT TIMESTAMP,
        DEPRECATED_AT TIMESTAMP,
        OBSOLETE_AT TIMESTAMP)';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_SIL_SCOPED_IDENTIFIER
        ON MDR.SCOPED_IDENTIFIER_LIFECYCLE (SCOPED_IDENTIFIER_ID)';
  END IF;

  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'SCOPED_IDENTIFIER' AND COLUMN_NAME = 'VERSION_STATUS';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.SCOPED_IDENTIFIER_LIFECYCLE
        (ID, SCOPED_IDENTIFIER_ID, IDENTIFIER_CREATION_MODE, VERSION_CREATION_MODE,
         VERSION_STATUS, CREATED_AT, PUBLISHED_AT, DEPRECATED_AT, OBSOLETE_AT)
    SELECT NEWID(), ID, IDENTIFIER_CREATION_MODE, VERSION_CREATION_MODE,
           VERSION_STATUS, CREATED_AT, PUBLISHED_AT, DEPRECATED_AT, OBSOLETE_AT
    FROM MDR.SCOPED_IDENTIFIER';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN IDENTIFIER_CREATION_MODE';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN VERSION_CREATION_MODE';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN VERSION_STATUS';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN CREATED_AT';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN PUBLISHED_AT';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN DEPRECATED_AT';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SCOPED_IDENTIFIER DROP COLUMN OBSOLETE_AT';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
