-- 清除 MDR.INDIVIDUAL 的两个非标准列，回归 ISO/IEC 11179-3:2023 §6.3.2：
-- Individual 的标准属性仅有 name / title / mail_address / email_address / phone_number（+ id）。
--   1. identifier —— 应用曾自行添加（V20260917001），标准无此属性，本次删除。
--   2. avatar     —— 头像语义归位为纯账号级，迁到 EXT.ACCOUNT.AVATAR（account 本体在 ext schema）。
--
-- 搬迁语义：把已绑定到账号的 Individual 的 avatar 复制到对应 EXT.ACCOUNT.AVATAR；
-- 未被任何账号引用的孤儿 Individual 其 avatar 随列删除一并丢失，属已知可接受。
-- 达梦方言：逐语句独立 PL/SQL 块守卫，列存在性查 ALL_TAB_COLUMNS，DDL 走 EXECUTE IMMEDIATE；
-- 与 SQL Server 版本语义一致。迁移不可重复执行（Flyway 一次语义），守卫仅为跨环境兜底。

-- 0. EXT.ACCOUNT.AVATAR（account 本体在 ext schema）
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='ACCOUNT';
  IF n = 1 THEN
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='EXT' AND TABLE_NAME='ACCOUNT' AND COLUMN_NAME='AVATAR';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE EXT.ACCOUNT ADD AVATAR CLOB'; END IF;
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 1. 数据搬迁：MDR.INDIVIDUAL.AVATAR -> EXT.ACCOUNT.AVATAR
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='INDIVIDUAL' AND COLUMN_NAME='AVATAR';
  IF n = 1 THEN
    EXECUTE IMMEDIATE
      'UPDATE EXT.ACCOUNT a
          SET a.AVATAR = (SELECT i.AVATAR FROM MDR.INDIVIDUAL i WHERE i.id = a.individual_id)
        WHERE a.individual_id IS NOT NULL';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 2. 删除 MDR.INDIVIDUAL.AVATAR
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='INDIVIDUAL' AND COLUMN_NAME='AVATAR';
  IF n = 1 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.INDIVIDUAL DROP COLUMN AVATAR'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

