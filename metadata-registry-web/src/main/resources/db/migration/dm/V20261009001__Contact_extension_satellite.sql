-- 账号绑定卫星表归位（personal-no-login-registrar-default，详见 sqlite 同名脚本头注释）：
-- EXT.CONTACT_ACCOUNT_BINDING 收敛为 EXT.CONTACT 卫星表（CONTACT_ID 即 PK）。
-- 达梦方言：逐语句独立 PL/SQL 块守卫，存在性查 ALL_TABLES，DDL 走 EXECUTE IMMEDIATE；
-- EXT schema 由 DBA 预建（V20260901014 前置，同 dm 目录惯例）。待达梦实例实测（项目惯例）。
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'CONTACT';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.CONTACT (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        ACCOUNT_ID CHAR(36) NOT NULL)';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_EXT_CONTACT_ACCOUNT
        ON EXT.CONTACT (ACCOUNT_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

DECLARE
  src NUMBER; dst NUMBER;
BEGIN
  SELECT COUNT(*) INTO src FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='CONTACT_ACCOUNT_BINDING';
  SELECT COUNT(*) INTO dst FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='CONTACT';
  IF src = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO EXT.CONTACT (ID, ACCOUNT_ID)
      SELECT CONTACT_ID, ACCOUNT_ID FROM EXT.CONTACT_ACCOUNT_BINDING
      WHERE NOT EXISTS (SELECT 1 FROM EXT.CONTACT e WHERE e.ID = CONTACT_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
