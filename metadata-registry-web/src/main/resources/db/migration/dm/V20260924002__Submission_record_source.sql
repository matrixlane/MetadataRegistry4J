-- SubmissionRecord 应用扩展属性 source（align-submission-record-to-iso）：
-- 区分工作空间提交（USER_SUBMISSION）与历史脏数据（SYSTEM_DRAFT）。
-- 历史脏数据：迁移前已存在的 SR 行（旧实现"编辑保存即新建"产生）一律标注 SYSTEM_DRAFT。
-- 新代码路径一律显式写 USER_SUBMISSION，SYSTEM_DRAFT 实例不再产生。
-- 达梦不支持 ALTER TABLE ADD COLUMN IF NOT EXISTS；用存储过程探测列存在性。
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='SUBMISSION_RECORD' AND COLUMN_NAME='SOURCE';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SUBMISSION_RECORD ADD SOURCE VARCHAR(32)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

UPDATE MDR.SUBMISSION_RECORD SET SOURCE = 'SYSTEM_DRAFT' WHERE SOURCE IS NULL;