-- 收尾清理（personal-no-login-registrar-default，详见 sqlite 同名脚本头注释）：
-- 1. EXT.CONTACT_ACCOUNT_BINDING 整表已由 EXT.CONTACT（V20261009001）承接，此处删除；
-- 2. 存量 PERSONAL 库清零强制改密/临时密码标志；团队库不动。
-- 达梦方言：PL/SQL 块守卫。待达梦实例实测（项目惯例）。
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'CONTACT_ACCOUNT_BINDING';
  IF tbl_exists = 1 THEN
    EXECUTE IMMEDIATE 'DROP TABLE EXT.CONTACT_ACCOUNT_BINDING';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

DECLARE
  personal NUMBER;
BEGIN
  SELECT COUNT(*) INTO personal FROM EXT.SYSTEM_SETTING
    WHERE SETTING_KEY = 'system.edition' AND SETTING_VALUE = 'PERSONAL';
  IF personal = 1 THEN
    EXECUTE IMMEDIATE 'UPDATE EXT.ACCOUNT
      SET FORCE_PASSWORD_RESET = 0, TEMP_PASSWORD_USED = 0
      WHERE EXISTS (SELECT 1 FROM EXT.SYSTEM_SETTING
                     WHERE SETTING_KEY = ''system.edition'' AND SETTING_VALUE = ''PERSONAL'')';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
