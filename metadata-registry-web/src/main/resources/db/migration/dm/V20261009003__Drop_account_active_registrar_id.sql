-- 删除 EXT.ACCOUNT.ACTIVE_REGISTRAR_ID 列（personal-no-login-registrar-default，详见 sqlite 同名脚本）。
-- 达梦方言：PL/SQL 块守卫。待达梦实例实测（项目惯例）。
DECLARE
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'ACCOUNT' AND COLUMN_NAME = 'ACTIVE_REGISTRAR_ID';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE EXT.ACCOUNT DROP COLUMN ACTIVE_REGISTRAR_ID';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
