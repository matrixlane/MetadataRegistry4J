-- 1.5 补标准缺失属性(5.2/5.3/5.4)库结构部分
-- valid_period 回填:start_date_time 取 administered_item.creation_date_time,无管理项兜底当前时间
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='CONCEPTUAL_DOMAIN' AND COLUMN_NAME='START_DATE_TIME';
  IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.CONCEPTUAL_DOMAIN ADD START_DATE_TIME TIMESTAMP WITH TIME ZONE'; END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='CONCEPTUAL_DOMAIN' AND COLUMN_NAME='END_DATE_TIME';
  IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.CONCEPTUAL_DOMAIN ADD END_DATE_TIME TIMESTAMP WITH TIME ZONE'; END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='CONCEPTUAL_DOMAIN' AND COLUMN_NAME='DIMENSIONALITY_ID';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.CONCEPTUAL_DOMAIN ADD DIMENSIONALITY_ID CHAR(36)';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.CONCEPTUAL_DOMAIN ADD CONSTRAINT FK_CD_DIMENSIONALITY FOREIGN KEY (DIMENSIONALITY_ID) REFERENCES MDR.DIMENSIONALITY(ID)';
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='ENUMERATED_CONCEPTUAL_DOMAIN' AND COLUMN_NAME='EXPANDED_ON_DATETIME';
  IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.ENUMERATED_CONCEPTUAL_DOMAIN ADD EXPANDED_ON_DATETIME TIMESTAMP WITH TIME ZONE'; END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='ENUMERATED_CONCEPTUAL_DOMAIN' AND COLUMN_NAME='LOCKED_DATETIME';
  IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.ENUMERATED_CONCEPTUAL_DOMAIN ADD LOCKED_DATETIME TIMESTAMP WITH TIME ZONE'; END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='MDR' AND TABLE_NAME='DATA_TYPE' AND COLUMN_NAME='ANNOTATION';
  IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.DATA_TYPE ADD ANNOTATION NVARCHAR2(2000)'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.CONCEPTUAL_DOMAIN cd SET START_DATE_TIME =
    (SELECT ai.CREATION_DATE_TIME FROM MDR.IDENTIFIED_ITEM ii JOIN MDR.ADMINISTERED_ITEM ai ON ai.ID = ii.ID WHERE ii.ITEM_ID = cd.ID)
    WHERE START_DATE_TIME IS NULL AND END_DATE_TIME IS NULL';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.CONCEPTUAL_DOMAIN SET START_DATE_TIME = SYSTIMESTAMP WHERE START_DATE_TIME IS NULL AND END_DATE_TIME IS NULL';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
