-- 3.1 Contact.account 扩展关联剥为卫星实体(ISO/IEC 11179 标准实体只留标准属性)
DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'CONTACT_ACCOUNT_BINDING';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MDR.CONTACT_ACCOUNT_BINDING (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        CONTACT_ID CHAR(36) NOT NULL,
        ACCOUNT_ID CHAR(36) NOT NULL)';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_CAB_CONTACT
        ON MDR.CONTACT_ACCOUNT_BINDING (CONTACT_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_CAB_ACCOUNT
        ON MDR.CONTACT_ACCOUNT_BINDING (ACCOUNT_ID)';
  END IF;

  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'CONTACT' AND COLUMN_NAME = 'ACCOUNT_ID';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.CONTACT_ACCOUNT_BINDING (ID, CONTACT_ID, ACCOUNT_ID)
    SELECT NEWID(), ID, ACCOUNT_ID
    FROM MDR.CONTACT
    WHERE ACCOUNT_ID IS NOT NULL';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.CONTACT DROP COLUMN ACCOUNT_ID';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
