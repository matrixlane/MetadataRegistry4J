-- 2.3 Namespace 标识符治理扩展属性剥为卫星实体(ISO/IEC 11179 标准实体只留标准属性)
DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'NAMESPACE_IDENTIFIER_SETTINGS';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MDR.NAMESPACE_IDENTIFIER_SETTINGS (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        NAMESPACE_ID CHAR(36) NOT NULL,
        VERSIONING_POLICY VARCHAR(32),
        IDENTIFIER_INPUT_MODE VARCHAR(32),
        VERSION_INPUT_MODE VARCHAR(32),
        MANUAL_IDENTIFIER_PATTERN VARCHAR(255))';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_NIS_NAMESPACE
        ON MDR.NAMESPACE_IDENTIFIER_SETTINGS (NAMESPACE_ID)';
  END IF;

  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'NAMESPACE' AND COLUMN_NAME = 'VERSIONING_POLICY';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.NAMESPACE_IDENTIFIER_SETTINGS
        (ID, NAMESPACE_ID, VERSIONING_POLICY, IDENTIFIER_INPUT_MODE,
         VERSION_INPUT_MODE, MANUAL_IDENTIFIER_PATTERN)
    SELECT NEWID(), ID, VERSIONING_POLICY, IDENTIFIER_INPUT_MODE,
           VERSION_INPUT_MODE, MANUAL_IDENTIFIER_PATTERN
    FROM MDR.NAMESPACE';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.NAMESPACE DROP COLUMN VERSIONING_POLICY';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.NAMESPACE DROP COLUMN IDENTIFIER_INPUT_MODE';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.NAMESPACE DROP COLUMN VERSION_INPUT_MODE';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.NAMESPACE DROP COLUMN MANUAL_IDENTIFIER_PATTERN';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
