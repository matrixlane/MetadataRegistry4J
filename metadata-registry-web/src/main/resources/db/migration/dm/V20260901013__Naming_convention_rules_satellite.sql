-- 3.3 NamingConvention.rulesJson 扩展属性剥为卫星实体(ISO/IEC 11179 标准实体只留标准属性)
DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'NAMING_CONVENTION_RULES';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MDR.NAMING_CONVENTION_RULES (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        NAMING_CONVENTION_ID CHAR(36) NOT NULL,
        RULES_JSON CLOB)';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_NCR_CONVENTION
        ON MDR.NAMING_CONVENTION_RULES (NAMING_CONVENTION_ID)';
  END IF;

  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'NAMING_CONVENTION' AND COLUMN_NAME = 'RULES_JSON';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.NAMING_CONVENTION_RULES (ID, NAMING_CONVENTION_ID, RULES_JSON)
    SELECT NEWID(), ID, RULES_JSON
    FROM MDR.NAMING_CONVENTION
    WHERE RULES_JSON IS NOT NULL';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.NAMING_CONVENTION DROP COLUMN RULES_JSON';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
