-- 1.9 Slot 恢复标准属性名 type(ISO/IEC 11179-3:2023 表 11:type 0..1 String)
DECLARE
  col_exists NUMBER;
  type_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'SLOT' AND COLUMN_NAME = 'VALUE_DATATYPE';
  SELECT COUNT(*) INTO type_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'SLOT' AND COLUMN_NAME = 'TYPE';
  IF col_exists = 1 AND type_exists = 1 THEN
    EXECUTE IMMEDIATE 'UPDATE MDR.SLOT SET TYPE = VALUE_DATATYPE WHERE TYPE IS NULL AND VALUE_DATATYPE IS NOT NULL';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SLOT DROP COLUMN VALUE_DATATYPE';
  ELSIF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.SLOT RENAME COLUMN VALUE_DATATYPE TO TYPE';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
