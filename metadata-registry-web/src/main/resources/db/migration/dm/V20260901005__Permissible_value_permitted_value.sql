-- 5.1 PermissibleValue.permitted_value(ISO/IEC 11179-31:2023 表 6 / 7.4.2.12.4,多重性 1)
-- 回填策略:取各允许值的首选指称符号(语言优先 zh-CN > en-US > 其他)。
DECLARE
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'PERMISSIBLE_VALUE' AND COLUMN_NAME = 'PERMITTED_VALUE';
  IF col_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.PERMISSIBLE_VALUE ADD PERMITTED_VALUE NVARCHAR2(255)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
    UPDATE MDR.PERMISSIBLE_VALUE pv
    SET PERMITTED_VALUE = (
      SELECT VAL FROM (
        SELECT d."value" AS VAL,
               ROW_NUMBER() OVER (
                 ORDER BY CASE li.LANGUAGE_IDENTIFIER
                            WHEN 'zh-CN' THEN 0 WHEN 'en-US' THEN 1 ELSE 2 END, d."value"
               ) AS RN
        FROM MDR.DESIGNATION d
        LEFT JOIN MDR.LANGUAGE_IDENTIFICATION li ON d.LANGUAGE_ID = li.ID
        WHERE d.ITEM_ID = pv.ID
      ) WHERE RN = 1
    )
    WHERE PERMITTED_VALUE IS NULL
  ]';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.PERMISSIBLE_VALUE SET PERMITTED_VALUE = '''' WHERE PERMITTED_VALUE IS NULL';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE MDR.PERMISSIBLE_VALUE MODIFY PERMITTED_VALUE NVARCHAR2(255) NOT NULL';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
