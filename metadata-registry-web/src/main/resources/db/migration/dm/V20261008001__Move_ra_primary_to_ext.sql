-- MDR.REGISTRATION_AUTHORITY.IS_PRIMARY 迁出至 EXT 卫星表（move-ra-primary-to-ext，详见 sqlite 同名脚本头注释）：
-- 建 EXT.REGISTRATION_AUTHORITY（1:1 按 id）→ 数据搬迁（INSERT SELECT）→ 删 MDR 列。
-- 既有库已应用 V20261005001（列存在），守卫保证只搬一次、删一次；幂等搬运不丢既有行。
-- 达梦方言：逐语句独立 PL/SQL 块守卫，存在性查 ALL_TABLES / ALL_TAB_COLUMNS，
-- DDL 走 EXECUTE IMMEDIATE；EXT schema 由 DBA 预建（V20260901014 前置，同 dm 目录惯例）。
-- 待达梦实例实测（项目惯例）。

-- 0. EXT.REGISTRATION_AUTHORITY 卫星表
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'REGISTRATION_AUTHORITY';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.REGISTRATION_AUTHORITY (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        IS_PRIMARY BIT DEFAULT 0 NOT NULL)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 1. 数据搬迁：MDR.REGISTRATION_AUTHORITY.IS_PRIMARY -> EXT.REGISTRATION_AUTHORITY
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'REGISTRATION_AUTHORITY' AND COLUMN_NAME = 'IS_PRIMARY';
  IF n = 1 THEN
    EXECUTE IMMEDIATE
      'INSERT INTO EXT.REGISTRATION_AUTHORITY (ID, IS_PRIMARY)
         SELECT ID, IS_PRIMARY FROM MDR.REGISTRATION_AUTHORITY';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 2. 删除 MDR.REGISTRATION_AUTHORITY.IS_PRIMARY
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'REGISTRATION_AUTHORITY' AND COLUMN_NAME = 'IS_PRIMARY';
  IF n = 1 THEN EXECUTE IMMEDIATE 'ALTER TABLE MDR.REGISTRATION_AUTHORITY DROP COLUMN IS_PRIMARY'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
