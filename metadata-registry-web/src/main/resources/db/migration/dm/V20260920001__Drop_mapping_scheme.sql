-- 达梦：逐语句独立 PL/SQL 块守卫，幂等；DDL 走动态 SQL。待达梦实例实测（KNOWN_FAILURES 同款遗留）。
-- 先动态删除引用这两表的全部外键（Hibernate ddl-auto 生成的 FK 命名不可预测）。
DECLARE
  CURSOR c_fk IS
    SELECT acc.owner, acc.table_name, acc.constraint_name
    FROM all_constraints acc
    WHERE acc.constraint_type = 'R'
      AND acc.r_owner = 'EXT'
      AND acc.r_constraint_name IN (
        SELECT ac.constraint_name FROM all_constraints ac
        WHERE ac.constraint_type IN ('P','U')
          AND ac.owner = 'EXT'
          AND ac.table_name IN ('MAPPING_SCHEME','MAPPING_SUBSCRIPTION'));
BEGIN
  FOR r IN c_fk LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.owner || '.' || r.table_name ||
                      ' DROP CONSTRAINT ' || r.constraint_name;
  END LOOP;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='MAPPING_SCHEME';
  IF n = 1 THEN EXECUTE IMMEDIATE 'DROP TABLE EXT.MAPPING_SCHEME'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
