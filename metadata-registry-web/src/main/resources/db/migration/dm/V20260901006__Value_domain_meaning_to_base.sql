-- 5.6 value_domain_meaning 提升到 ValueDomain 基类(ISO/IEC 11179-31:2023 7.2.3.1 / 7.4.4.1)
DECLARE
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'VALUE_DOMAIN' AND COLUMN_NAME = 'CONCEPTUAL_DOMAIN_ID';
  IF col_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.VALUE_DOMAIN ADD CONCEPTUAL_DOMAIN_ID CHAR(36)';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.VALUE_DOMAIN ADD CONSTRAINT FK_VD_CONCEPTUAL_DOMAIN
      FOREIGN KEY (CONCEPTUAL_DOMAIN_ID) REFERENCES MDR.CONCEPTUAL_DOMAIN(ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.VALUE_DOMAIN vd SET CONCEPTUAL_DOMAIN_ID =
    (SELECT dvd.DESCRIBED_CONCEPTUAL_DOMAIN_ID FROM MDR.DESCRIBED_VALUE_DOMAIN dvd WHERE dvd.ID = vd.ID)
    WHERE CONCEPTUAL_DOMAIN_ID IS NULL AND EXISTS
    (SELECT 1 FROM MDR.DESCRIBED_VALUE_DOMAIN dvd WHERE dvd.ID = vd.ID AND dvd.DESCRIBED_CONCEPTUAL_DOMAIN_ID IS NOT NULL)';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.VALUE_DOMAIN vd SET CONCEPTUAL_DOMAIN_ID =
    (SELECT levd.LOCAL_ENUMERATED_CONCEPTUAL_DOMAIN_ID FROM MDR.LOCAL_ENUMERATED_VALUE_DOMAIN levd WHERE levd.ID = vd.ID)
    WHERE CONCEPTUAL_DOMAIN_ID IS NULL AND EXISTS
    (SELECT 1 FROM MDR.LOCAL_ENUMERATED_VALUE_DOMAIN levd WHERE levd.ID = vd.ID AND levd.LOCAL_ENUMERATED_CONCEPTUAL_DOMAIN_ID IS NOT NULL)';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'UPDATE MDR.VALUE_DOMAIN vd SET CONCEPTUAL_DOMAIN_ID =
    (SELECT revd.REFERENCED_CONCEPTUAL_DOMAIN_ID FROM MDR.REFERENCE_ENUMERATED_VALUE_DOMAIN revd WHERE revd.ID = vd.ID)
    WHERE CONCEPTUAL_DOMAIN_ID IS NULL AND EXISTS
    (SELECT 1 FROM MDR.REFERENCE_ENUMERATED_VALUE_DOMAIN revd WHERE revd.ID = vd.ID AND revd.REFERENCED_CONCEPTUAL_DOMAIN_ID IS NOT NULL)';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE MDR.DESCRIBED_VALUE_DOMAIN DROP COLUMN DESCRIBED_CONCEPTUAL_DOMAIN_ID';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE MDR.LOCAL_ENUMERATED_VALUE_DOMAIN DROP COLUMN LOCAL_ENUMERATED_CONCEPTUAL_DOMAIN_ID';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE MDR.REFERENCE_ENUMERATED_VALUE_DOMAIN DROP COLUMN REFERENCED_CONCEPTUAL_DOMAIN_ID';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
