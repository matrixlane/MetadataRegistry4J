DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  -- 1. 测试残留表与冗余表
  FOR r IN (SELECT 'DEFINITION_SERVICE_TEST$TEST_ITEM' nm FROM DUAL UNION ALL
            SELECT 'DESIGNATION_SERVICE_TEST$TEST_ITEM' FROM DUAL UNION ALL
            SELECT 'ITEM_ADMINISTRATION_SERVICE_TEST$TEST_ITEM' FROM DUAL UNION ALL
            SELECT 'VALUE_MEANING_PERMISSIBLE_VALUE_MEANING' FROM DUAL)
  LOOP
    SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
      WHERE OWNER = 'MDR' AND TABLE_NAME = r.nm;
    IF tbl_exists = 1 THEN
      EXECUTE IMMEDIATE 'DROP TABLE MDR."' || r.nm || '" CASCADE CONSTRAINTS';
    END IF;
  END LOOP;

  -- 2. 表更名（旧名存在且新名不存在才执行——ddl-auto 可能已按新名预建）
  FOR r IN (SELECT 'CONCEPTUAL_DOMAIN_DEC' o, 'DATA_ELEMENT_CONCEPT_DOMAIN' n FROM DUAL UNION ALL
            SELECT 'DESIGNATION_CONTEXT_RELATION', 'DESIGNATION_CONTEXT' FROM DUAL UNION ALL
            SELECT 'DEFINITION_CONTEXT_RELATION', 'DEFINITION_CONTEXT' FROM DUAL UNION ALL
            SELECT 'ITEM_MAPPING_SUBJECT', 'SUBJECT_MAPPING' FROM DUAL UNION ALL
            SELECT 'ITEM_MAPPING_OBJECT', 'OBJECT_MAPPING' FROM DUAL UNION ALL
            SELECT 'DESIGNATION_NAMING_CONVENTION', 'NAMING_CONVENTION_CONFORMANCE' FROM DUAL UNION ALL
            SELECT 'NAMESPACE_NAMING_CONVENTION', 'NAMING_CONVENTION_UTILIZATION' FROM DUAL UNION ALL
            SELECT 'UNIT_OF_MEASURE_MEASURE_CLASS', 'UNIT_OF_MEASURE_CLASS' FROM DUAL UNION ALL
            SELECT 'SUBMISSION_RECORD_REGISTERED_ITEM', 'REGISTERED_ITEM_SUBMISSION_RECORD' FROM DUAL)
  LOOP
    SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
      WHERE OWNER = 'MDR' AND TABLE_NAME = r.o;
    IF tbl_exists = 1 THEN
      SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
        WHERE OWNER = 'MDR' AND TABLE_NAME = r.n;
      IF tbl_exists = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE MDR.' || r.o || ' RENAME TO ' || r.n;
      END IF;
    END IF;
  END LOOP;

  -- 3. registration_transition_* 三表迁 ext：达梦跳过（遗留任务）
END;
/

-- 2.5 子表回填：内联值先入子表再删列（幂等去重；本库审计为空、老快照库非空）
DECLARE
  col_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO col_count FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'SLOT' AND COLUMN_NAME = 'VALUE';
  IF col_count = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.SLOT_VALUE (SLOT_ID, VALUE)
      SELECT o.ID, o.VALUE FROM MDR.SLOT o WHERE o.VALUE IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM MDR.SLOT_VALUE v WHERE v.SLOT_ID = o.ID AND v.VALUE = o.VALUE)';
  END IF;
  SELECT COUNT(*) INTO col_count FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'ROLE' AND COLUMN_NAME = 'EMAIL_ADDRESS';
  IF col_count = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.ROLE_EMAIL (ROLE_ID, VALUE)
      SELECT o.ID, o.EMAIL_ADDRESS FROM MDR.ROLE o WHERE o.EMAIL_ADDRESS IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM MDR.ROLE_EMAIL v WHERE v.ROLE_ID = o.ID AND v.VALUE = o.EMAIL_ADDRESS)';
  END IF;
  SELECT COUNT(*) INTO col_count FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'ROLE' AND COLUMN_NAME = 'PHONE_NUMBER';
  IF col_count = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.ROLE_PHONE (ROLE_ID, VALUE)
      SELECT o.ID, o.PHONE_NUMBER FROM MDR.ROLE o WHERE o.PHONE_NUMBER IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM MDR.ROLE_PHONE v WHERE v.ROLE_ID = o.ID AND v.VALUE = o.PHONE_NUMBER)';
  END IF;
END;
/

-- 4. 删非标准列（逐列守卫；全部列经审计 0 行非空，零数据搬迁）
DECLARE
  col_count NUMBER;
BEGIN
  FOR r IN (SELECT 'NAMESPACE' t, 'IDENTIFIER_INPUT_MODE' c FROM DUAL UNION ALL
            SELECT 'NAMESPACE', 'MANUAL_IDENTIFIER_PATTERN' FROM DUAL UNION ALL
            SELECT 'NAMESPACE', 'VERSION_INPUT_MODE' FROM DUAL UNION ALL
            SELECT 'NAMESPACE', 'VERSIONING_POLICY' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'IDENTIFIER_CREATION_MODE' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'VERSION_CREATION_MODE' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'VERSION_STATUS' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'CREATED_AT' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'PUBLISHED_AT' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'DEPRECATED_AT' FROM DUAL UNION ALL
            SELECT 'SCOPED_IDENTIFIER', 'OBSOLETE_AT' FROM DUAL UNION ALL
            SELECT 'NAMING_CONVENTION', 'RULES_JSON' FROM DUAL UNION ALL
            SELECT 'LANGUAGE_IDENTIFICATION', 'ENABLED' FROM DUAL UNION ALL
            SELECT 'CONTACT', 'ACCOUNT_ID' FROM DUAL UNION ALL
            SELECT 'DATA_TYPE_SCHEME', 'REFERENCE' FROM DUAL UNION ALL
            SELECT 'SLOT', 'VALUE' FROM DUAL UNION ALL
            SELECT 'SLOT', 'VALUE_DATATYPE' FROM DUAL UNION ALL
            SELECT 'ROLE', 'EMAIL_ADDRESS' FROM DUAL UNION ALL
            SELECT 'ROLE', 'PHONE_NUMBER' FROM DUAL UNION ALL
            SELECT 'DESIGNATION', 'ACCEPTABILITY' FROM DUAL UNION ALL
            SELECT 'DEFINITION', 'ACCEPTABILITY' FROM DUAL UNION ALL
            SELECT 'SUBMISSION_RECORD', 'SOURCE' FROM DUAL)
  LOOP
    SELECT COUNT(*) INTO col_count FROM ALL_TAB_COLUMNS
      WHERE OWNER = 'MDR' AND TABLE_NAME = r.t AND COLUMN_NAME = r.c;
    IF col_count = 1 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE MDR.' || r.t || ' DROP COLUMN ' || r.c || ' CASCADE';
    END IF;
  END LOOP;
EXCEPTION WHEN OTHERS THEN NULL;
END;
