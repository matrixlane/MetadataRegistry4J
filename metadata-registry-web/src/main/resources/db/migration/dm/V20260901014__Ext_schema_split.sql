-- 阶段 3 MDR/EXT schema 拆分:23 张扩展表从 MDR 迁入 EXT。
-- 前置:EXT 模式须由 DBA 预建(CREATE USER/SCHEMA EXT)并对应用用户授权;
-- EXT 不存在时 CTAS 报错,由 EXCEPTION 吞掉,该表跳过(启动日志可复查)。
-- 逐表独立 PL/SQL 块:MDR.<T> 存在且 EXT.<T> 不存在才搬,幂等。

DECLARE
  src NUMBER; dst NUMBER;
BEGIN
  SELECT COUNT(*) INTO src FROM ALL_TABLES WHERE OWNER='MDR' AND TABLE_NAME='CLASSIFICATION_SCHEME';
  SELECT COUNT(*) INTO dst FROM ALL_TABLES WHERE OWNER='EXT' AND TABLE_NAME='CLASSIFICATION_SCHEME';
  IF src = 1 AND dst = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.CLASSIFICATION_SCHEME AS SELECT * FROM MDR.CLASSIFICATION_SCHEME';
    EXECUTE IMMEDIATE 'ALTER TABLE EXT.CLASSIFICATION_SCHEME ADD PRIMARY KEY (ID)';
    EXECUTE IMMEDIATE 'DROP TABLE MDR.CLASSIFICATION_SCHEME';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

