-- 3.2 LanguageIdentification.enabled 扩展属性剥为卫星实体(ISO/IEC 11179 标准实体只留标准属性)
DECLARE
  tbl_exists NUMBER;
  col_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'LANGUAGE_GOVERNANCE';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MDR.LANGUAGE_GOVERNANCE (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        LANGUAGE_ID CHAR(36) NOT NULL,
        ENABLED BIT NOT NULL DEFAULT 1)';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_LG_LANGUAGE
        ON MDR.LANGUAGE_GOVERNANCE (LANGUAGE_ID)';
  END IF;

  SELECT COUNT(*) INTO col_exists FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'MDR' AND TABLE_NAME = 'LANGUAGE_IDENTIFICATION' AND COLUMN_NAME = 'ENABLED';
  IF col_exists = 1 THEN
    EXECUTE IMMEDIATE 'INSERT INTO MDR.LANGUAGE_GOVERNANCE (ID, LANGUAGE_ID, ENABLED)
    SELECT NEWID(), ID, COALESCE(ENABLED, 1)
    FROM MDR.LANGUAGE_IDENTIFICATION';
    EXECUTE IMMEDIATE 'ALTER TABLE MDR.LANGUAGE_IDENTIFICATION DROP COLUMN ENABLED';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
