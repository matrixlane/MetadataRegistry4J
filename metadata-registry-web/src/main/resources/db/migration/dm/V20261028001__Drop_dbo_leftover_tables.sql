-- dbo 遗留表清理（cleanup-dbo-leftover-tables）达梦侧
-- DM 无 dbo 概念；清理 MDR（及防御性检查 EXT）owner 下 10 张非活表。
-- idiom 同 V20260901015：PL/SQL 块 + ALL_TABLES owner 守卫 + EXCEPTION WHEN OTHERS 容错。
-- 不触碰 INTEROP_MAPPING / VERSION_HISTORY（EXT 下活表）。

-- 零、防御性修复 FLYWAY_SCHEMA_HISTORY 的 INSTALLED_ON 默认值（同 SQL Server 侧隐患：
-- Flyway 写历史行省略该列、依赖列默认值；缺失则报 NOT NULL 约束错误，本迁移也无法记录）
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
   WHERE OWNER='EXT' AND TABLE_NAME='FLYWAY_SCHEMA_HISTORY'
     AND COLUMN_NAME='INSTALLED_ON' AND DATA_DEFAULT IS NULL;
  IF n = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE EXT.FLYWAY_SCHEMA_HISTORY MODIFY (INSTALLED_ON DEFAULT SYSDATE)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

