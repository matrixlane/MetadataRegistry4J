-- 忠实标准模型：一条映射可有 1..* 主体与 1..* 客体（详见 sqlite 同名脚本）。
-- 达梦：PL/SQL 块守卫，幂等。待达梦实例实测。
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='MDR' AND INDEX_NAME='UK_IMS_MAPPING';
  IF n = 1 THEN EXECUTE IMMEDIATE 'DROP INDEX MDR.UK_IMS_MAPPING'; END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
