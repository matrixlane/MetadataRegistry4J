-- 语言名称/地区名称扩展卫星表:EXT.LANGUAGE_IDENTIFICATION,与标准表
-- MDR.LANGUAGE_IDENTIFICATION 同名不同 schema(设计 2026-09-19-language-identification-extension)。
DECLARE
  tbl_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO tbl_exists FROM ALL_TABLES
    WHERE OWNER = 'EXT' AND TABLE_NAME = 'LANGUAGE_IDENTIFICATION';
  IF tbl_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE EXT.LANGUAGE_IDENTIFICATION (
        ID CHAR(36) NOT NULL PRIMARY KEY,
        LANGUAGE_ID CHAR(36) NOT NULL,
        LANGUAGE_NAME VARCHAR(255),
        TERRITORY_NAME VARCHAR(255))';
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_LIEXT_LANGUAGE
        ON EXT.LANGUAGE_IDENTIFICATION (LANGUAGE_ID)';
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
